#!/usr/bin/env node
// Writes docs/tools.md from the tool definitions, so the reference cannot drift from the code.
// Run `npm run docs:tools` to rewrite it, or pass --check to fail when it is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { z } from 'zod';
import { allTools } from '../dist/tools.js';

const target = new URL('../docs/tools.md', import.meta.url);

// One line per effect, so readers see what a tool does to the outside world.
const EFFECTS = {
  read: 'Reads data only.',
  create: 'Creates something new in your organization.',
  update: 'Overwrites existing settings.',
  external: 'Acts on WhatsApp or Meta, so customers or reviewers see the result.',
};

// Describes one input type in words for the table.
function typeOf(schema) {
  if (schema.enum) return schema.enum.map((value) => `\`${value}\``).join(', ');
  if (schema.anyOf) return schema.anyOf.map(typeOf).join(' or ');
  if (schema.type === 'array') {
    const limit = schema.maxItems ? `, at most ${schema.maxItems}` : '';
    return `list of ${typeOf(schema.items ?? {})}${limit}`;
  }
  if (schema.type === 'object') return 'object';
  if (schema.format === 'uuid') return 'UUID';
  if (schema.type === 'integer') {
    if (schema.maximum !== undefined && schema.maximum < 1e9)
      return `integer ${schema.minimum ?? 0} to ${schema.maximum}`;
    return `integer, ${schema.minimum ?? 0} or more`;
  }
  if (schema.type === 'string' && schema.maxLength)
    return `string (up to ${schema.maxLength} characters)`;
  return schema.type ?? 'any';
}

// Builds the table of inputs for one tool.
function inputTable(tool) {
  const schema = z.toJSONSchema(tool.input, { io: 'input' });
  const required = new Set(schema.required ?? []);
  const rows = Object.entries(schema.properties ?? {}).map(([name, property]) => {
    const fallback = property.default === undefined ? '' : ` Defaults to \`${property.default}\`.`;
    const description = `${property.description ?? ''}${fallback}`.replaceAll('|', '\\|').trim();
    return `| \`${name}\` | ${typeOf(property).replaceAll('|', '\\|')} | ${required.has(name) ? 'yes' : 'no'} | ${description} |`;
  });
  return ['| Input | Type | Required | Description |', '| --- | --- | --- | --- |', ...rows].join(
    '\n',
  );
}

// Builds the whole document.
function render() {
  const sections = allTools.map((tool) =>
    [`## ${tool.name}`, '', tool.description, '', EFFECTS[tool.effect], '', inputTable(tool)].join(
      '\n',
    ),
  );
  return [
    '# Tool reference',
    '',
    'Do not edit this file by hand. Change the descriptions in `src/features/<domain>/tools.ts`, then run `npm run docs:tools`.',
    '',
    `The server exposes ${allTools.length} tools. Tools marked as reading data only stay available when \`WASSIST_READ_ONLY=true\`. All others are hidden in that mode.`,
    '',
    ...sections.flatMap((section) => [section, '']),
  ]
    .join('\n')
    .trimEnd()
    .concat('\n');
}

const next = render();
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {}
  if (current !== next) {
    process.stderr.write('docs/tools.md is out of date. Run `npm run docs:tools`.\n');
    process.exit(1);
  }
} else {
  writeFileSync(target, next);
}
